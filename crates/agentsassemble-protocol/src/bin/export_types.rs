use std::{fs, path::PathBuf};

use agentsassemble_protocol::{
    CommandAck, HUMAN_INVITE_JOIN_CODE_BYTES, HUMAN_INVITE_JOIN_CODE_PREFIX,
    HUMAN_INVITE_SIGNATURE_BYTES, HUMAN_INVITE_SIGNED_TOKEN_MAX_BYTES,
    HUMAN_INVITE_SIGNED_TOKEN_PREFIX, HostProductSurface, HttpMethod, HttpRouteSurface,
    PRODUCT_SURFACE_REVISION, RoomAction, RoomSnapshot, RoomStream, ServerProductSurface,
    Subscribed, TicketResponse,
};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../frontend/src/types/generated");
    fs::create_dir_all(&output)?;
    let config = Config::new()
        .with_out_dir(output.clone())
        .with_large_int("number")
        .with_import_extension(Some("js"));
    RoomSnapshot::export_all(&config)?;
    Subscribed::export_all(&config)?;
    CommandAck::export_all(&config)?;
    TicketResponse::export_all(&config)?;
    HttpMethod::export_all(&config)?;
    HttpRouteSurface::export_all(&config)?;
    RoomStream::export_all(&config)?;
    RoomAction::export_all(&config)?;
    ServerProductSurface::export_all(&config)?;
    HostProductSurface::export_all(&config)?;
    fs::write(
        output.join("PRODUCT_SURFACE_REVISION.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const PRODUCT_SURFACE_REVISION = {PRODUCT_SURFACE_REVISION} as const;\n"
        ),
    )?;
    fs::write(
        output.join("HUMAN_INVITE_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const HUMAN_INVITE_SIGNED_TOKEN_PREFIX = {HUMAN_INVITE_SIGNED_TOKEN_PREFIX:?} as const;\nexport const HUMAN_INVITE_JOIN_CODE_PREFIX = {HUMAN_INVITE_JOIN_CODE_PREFIX:?} as const;\nexport const HUMAN_INVITE_SIGNED_TOKEN_MAX_BYTES = {HUMAN_INVITE_SIGNED_TOKEN_MAX_BYTES} as const;\nexport const HUMAN_INVITE_SIGNATURE_BYTES = {HUMAN_INVITE_SIGNATURE_BYTES} as const;\nexport const HUMAN_INVITE_JOIN_CODE_BYTES = {HUMAN_INVITE_JOIN_CODE_BYTES} as const;\n"
        ),
    )?;
    Ok(())
}
