    export_operational_contracts(&output, &config)?;
    agentsassemble_domain::ProviderRequestResolution::export_all(&config)?;
    agentsassemble_protocol::AttendeeEntryPacket::export_all(&config)?;
    agentsassemble_protocol::CreateCompanionAttendeeInvite::export_all(&config)?;
    agentsassemble_protocol::CreateFriendAttendeeInvite::export_all(&config)?;
    agentsassemble_protocol::CreateConnectorInviteRequest::export_all(&config)?;
    agentsassemble_protocol::CreatedConnectorInvite::export_all(&config)?;
    PersonaAssetSummary::export_all(&config)?;
    agentsassemble_domain::SavedFriend::export_all(&config)?;
    agentsassemble_domain::SaveFriend::export_all(&config)?;
    Subscribed::export_all(&config)?;
    CommandAck::export_all(&config)?;
    TicketResponse::export_all(&config)?;
    HttpMethod::export_all(&config)?;
    HttpRouteSurface::export_all(&config)?;
    export_chat_contracts(&output, &config)?;
    RoomAction::export_all(&config)?;
    ServerProductSurface::export_all(&config)?;
    HostProductSurface::export_all(&config)?;
