fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../frontend/src/types/generated");
    fs::create_dir_all(&output)?;
    let config = Config::new()
        .with_out_dir(output.clone())
        .with_large_int("number")
        .with_import_extension(Some("js"));
    RoomSnapshot::export_all(&config)?;
    agentsassemble_domain::ProviderUsage::export_all(&config)?;
    agentsassemble_domain::ProviderRequestResolution::export_all(&config)?;
    agentsassemble_protocol::AttendeeEntryPacket::export_all(&config)?;
    agentsassemble_protocol::CreateCompanionAttendeeInvite::export_all(&config)?;
    agentsassemble_protocol::CreateFriendAttendeeInvite::export_all(&config)?;
    agentsassemble_protocol::CreateConnectorInviteRequest::export_all(&config)?;
    agentsassemble_protocol::CreatedConnectorInvite::export_all(&config)?;
    PersonaAssetSummary::export_all(&config)?;
    agentsassemble_domain::SavedFriend::export_all(&config)?;
    agentsassemble_domain::SaveFriend::export_all(&config)?;
    Subscribed::export_all(&config)?;
    CommandAck::export_all(&config)?;
    TicketResponse::export_all(&config)?;
    HttpMethod::export_all(&config)?;
    HttpRouteSurface::export_all(&config)?;
    export_chat_contracts(&output, &config)?;
    RoomAction::export_all(&config)?;
    ServerProductSurface::export_all(&config)?;
    HostProductSurface::export_all(&config)?;
    fs::write(
        output.join("PRODUCT_SURFACE_REVISION.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const PRODUCT_SURFACE_REVISION = {PRODUCT_SURFACE_REVISION} as const;\n"
        ),
    )?;
    fs::write(
        output.join("ROOM_ACTIONS.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const ROOM_ACTIONS = {} as const;\nexport const AGENT_CONTROL_ID_KEYS = {} as const;\n",
            serde_json::to_string(
                &RoomAction::ALL
                    .iter()
                    .filter(|action| action.supports_websocket())
                    .map(|action| action.as_str())
                    .collect::<Vec<_>>()
            )?,
            serde_json::to_string(&AGENT_CONTROL_ID_KEYS)?
        ),
    )?;
    fs::write(
        output.join("ROOM_SETTINGS_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const ROOM_LABEL_LIMIT = {} as const;\n",
            agentsassemble_domain::ROOM_LABEL_LIMIT,
        ),
    )?;
    fs::write(
        output.join("ROOM_HISTORY_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const ROOM_HISTORY_MAX_EVENTS = {ROOM_HISTORY_MAX_EVENTS} as const;\n"
        ),
    )?;
    fs::write(
        output.join("ROOM_SOCKET_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const MAX_ROOM_SOCKET_MESSAGE_BYTES = {MAX_ROOM_SOCKET_MESSAGE_BYTES} as const;\n"
        ),
    )?;
    fs::write(
        output.join("AGENT_PROFILE_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const AGENT_PROFILE_NAME_CHARACTER_LIMIT = {} as const;\n",
            agentsassemble_domain::AGENT_PROFILE_NAME_CHARACTER_LIMIT,
        ),
    )?;
    export_human_credential_contracts(&output)?;
    export_asset_contracts(&output)?;
    fs::write(
        output.join("ROOM_MESSAGE_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const MAX_MESSAGE_CHARACTERS = {MAX_MESSAGE_CHARACTERS} as const;\n"
        ),
    )?;
    fs::write(
        output.join("MESSAGE_PINS_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const MAX_CHANNEL_MESSAGE_PINS = {MAX_CHANNEL_MESSAGE_PINS} as const;\nexport const MAX_MESSAGE_EVENT_ID_BYTES = {MAX_MESSAGE_EVENT_ID_BYTES} as const;\n"
        ),
    )?;
    fs::write(
        output.join("MESSAGE_SEARCH_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const MESSAGE_SEARCH_PAGE_SIZE = {MESSAGE_SEARCH_PAGE_SIZE} as const;\nexport const MESSAGE_CONTEXT_RADIUS = {MESSAGE_CONTEXT_RADIUS} as const;\nexport const MAX_MESSAGE_SEARCH_QUERY_CHARACTERS = {MAX_MESSAGE_SEARCH_QUERY_CHARACTERS} as const;\nexport const MAX_MESSAGE_SEARCH_AUTHOR_CHARACTERS = {MAX_MESSAGE_SEARCH_AUTHOR_CHARACTERS} as const;\nexport const MAX_MESSAGE_SEARCH_CONTENT_CHARACTERS = {MAX_MESSAGE_SEARCH_CONTENT_CHARACTERS} as const;\nexport const MAX_MESSAGE_SEARCH_CURSOR_BYTES = {MAX_MESSAGE_SEARCH_CURSOR_BYTES} as const;\n"
        ),
    )?;
    fs::write(
        output.join("VOTE_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const MIN_VOTE_DURATION_SECONDS = {MIN_VOTE_DURATION_SECONDS} as const;\nexport const MAX_VOTE_DURATION_SECONDS = {MAX_VOTE_DURATION_SECONDS} as const;\nexport const VOTE_QUESTION_CHARACTER_LIMIT = {VOTE_QUESTION_CHARACTER_LIMIT} as const;\nexport const VOTE_OPTION_CHARACTER_LIMIT = {VOTE_OPTION_CHARACTER_LIMIT} as const;\nexport const MIN_VOTE_OPTIONS = {MIN_VOTE_OPTIONS} as const;\nexport const MAX_VOTE_OPTIONS = {MAX_VOTE_OPTIONS} as const;\n"
        ),
    )?;
    Ok(())
}

fn export_chat_contracts(
    output: &std::path::Path,
    config: &Config,
) -> Result<(), Box<dyn std::error::Error>> {
    agentsassemble_domain::ChannelHistoryPage::export_all(config)?;
    agentsassemble_domain::ChannelMessageSend::export_all(config)?;
    agentsassemble_domain::SideChatSnapshot::export_all(config)?;
    agentsassemble_domain::SideChatUpdate::export_all(config)?;
    agentsassemble_domain::SideChatSend::export_all(config)?;
    RoomStream::export_all(config)?;
    fs::write(
        output.join("ROOM_STREAMS.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const ROOM_STREAMS = {} as const;\n",
            serde_json::to_string(
                &RoomStream::ALL
                    .iter()
                    .map(|stream| stream.as_str())
                    .collect::<Vec<_>>()
            )?
        ),
    )?;
    fs::write(
        output.join("TEXT_CHAT_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const MAX_TEXT_CHAT_CHARACTERS = {} as const;\nexport const CHANNEL_HISTORY_PAGE_SIZE = {} as const;\nexport const CHANNEL_MESSAGE_EVENT_TYPE = {} as const;\n",
            agentsassemble_domain::MAX_TEXT_CHAT_CHARACTERS,
            agentsassemble_domain::CHANNEL_HISTORY_PAGE_SIZE,
            serde_json::to_string(agentsassemble_domain::CHANNEL_MESSAGE_EVENT_TYPE)?,
        ),
    )?;
    fs::write(
        output.join("SIDE_CHAT_WIRE.ts"),
        format!(
            "// Generated by agentsassemble-protocol. Do not edit.\nexport const SIDE_CHAT_MAX_MESSAGES = {} as const;\nexport const SIDE_CHAT_TTL_SECONDS = {} as const;\n",
            agentsassemble_domain::SIDE_CHAT_MAX_MESSAGES,
            agentsassemble_domain::SIDE_CHAT_TTL_SECONDS
        ),
    )?;
    Ok(())
}

